def name_of(code: int) -> str:
    if code == 0:
        return "zero"
    elif code == 1:
        return "n1"
    elif code == 2:
        return "n2"
    elif code == 3:
        return "n3"
    elif code == 4:
        return "n4"
    elif code == 5:
        return "n5"
    elif code == 6:
        return "n6"
    return "other"
