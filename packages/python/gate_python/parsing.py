"""Parses one source file into a Module and classifies it: generated, test, component."""

import ast
import tokenize

from gate_python import globs, lexing
from gate_python.model import Component, Config, Module, Problem, SourceFile

MARKER_LINES = 5
GENERATED_MARKERS = ("<auto-generated", "@generated")
SUFFIX = ".py"
PACKAGE_FILE = "__init__"


def is_generated(source: SourceFile, config: Config) -> bool:
    head = "\n".join(source.text.splitlines()[:MARKER_LINES])
    return globs.matches_any(source.path, config.generated) or any(marker in head for marker in GENERATED_MARKERS)


def module_of(source: SourceFile, config: Config) -> Module | Problem:
    try:
        tree = ast.parse(source.text)
        tokens = lexing.tokens_of(source.text)
    except SyntaxError as error:
        return Problem(source.path, error.lineno or 0, error.offset or 0, f"does not parse, {error.msg}. Fix the syntax error")
    except tokenize.TokenError as error:
        return Problem(source.path, error.args[1][0], error.args[1][1], f"does not parse, {error.args[0]}. Fix the syntax error")
    owner = _component(source.path, config)
    return Module(
        path=source.path,
        name=module_name(source.path),
        tree=tree,
        lines=tuple(source.text.splitlines()),
        comments=lexing.comments_of(tokens),
        code_lines=lexing.code_lines(tokens, tree),
        test=globs.matches_any(source.path, config.tests),
        component=owner.name,
        effect=owner.effect,
    )


def module_name(path: str) -> str:
    parts = path.removesuffix(SUFFIX).split("/")
    named = parts[:-1] if parts[-1] == PACKAGE_FILE and len(parts) > 1 else parts
    return ".".join(named)


def _component(path: str, config: Config) -> Component:
    owners = [component for component in config.components if globs.matches_any(path, component.paths)]
    return owners[0] if owners else Component("", (), False)
