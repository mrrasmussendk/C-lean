using System.Collections.Generic;
using System.Linq;
using System.Text.RegularExpressions;

namespace Gate.CSharp.Config;

internal sealed record Classification(GateConfig Config, IReadOnlyList<Component> Components);

/// <summary>Maps a root-relative path to test code, generated code and its component.</summary>
internal static class Classify
{
    private const int MarkerLines = 5;
    private static readonly string[] Markers = ["<auto-generated", "@generated"];
    private static readonly Component Unmapped = new("", [], false);

    public static bool IsTest(string path, Classification classification) =>
        Matches(classification.Config.Tests, path);

    public static bool IsGenerated(string path, IEnumerable<string> lines, Classification classification) =>
        Matches(classification.Config.Generated, path)
        || lines.Take(MarkerLines).Any(line => Markers.Any(line.Contains));

    public static Component ComponentOf(string path, Classification classification) =>
        classification.Components.FirstOrDefault(component => Matches(component.Paths, path), Unmapped);

    private static bool Matches(IReadOnlyList<Regex> patterns, string path) =>
        patterns.Any(pattern => pattern.IsMatch(path));
}
