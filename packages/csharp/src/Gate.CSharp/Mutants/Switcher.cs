using System.Collections.Generic;
using System.Linq;
using Gate.CSharp.Model;
using Gate.CSharp.Tracing;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Gate.CSharp.Mutants;

/// <summary>
/// Compiles mutants into a source file behind a switch: the expression that holds the mutated token
/// becomes `(Helper.Is("id") ? mutated : original)`. Nested expressions nest their switches in the
/// original branch; the mutated branch is the plain original text with the one token replaced.
/// </summary>
internal static class Switcher
{
    public const string HelperFile = "GateMutant.g.cs";
    private const string HelperPrefix = "GateMutant_";

    private const string Template = """
        // <auto-generated/>
        // Written by gate-csharp mutants --switch. The mutant named by GATE_MUTANT is active; it is read once per process.
        internal static class CLASS
        {
            private static readonly string Active = global::System.Environment.GetEnvironmentVariable("GATE_MUTANT") ?? "";

            public static bool Is(string id)
            {
                return Active.Length != 0 && string.Equals(Active, id, global::System.StringComparison.Ordinal);
            }
        }

        """;

    public static string HelperSource(string assembly) => Template.Replace("CLASS", HelperClass(assembly));

    public static string Rewrite(SourceFile file, IEnumerable<Site> sites)
    {
        var helper = HelperClass(file.Assembly);
        var edits = sites.OrderByDescending(site => Holder(site).Span.Length).ThenBy(site => site.Token.SpanStart)
            .SelectMany(site => Edits(site, helper));
        return TextEdits.Apply(file.Tree.GetText().ToString(), edits);
    }

    /// <summary>The id of the mutant a conditional expression switches, or empty when it is not a switch.</summary>
    public static string SwitchedId(ConditionalExpressionSyntax choice) =>
        choice.Condition is InvocationExpressionSyntax { ArgumentList.Arguments: [{ Expression: LiteralExpressionSyntax id }] } call
        && call.Expression.ToString().StartsWith($"global::{HelperPrefix}")
            ? id.Token.ValueText
            : "";

    /// <summary>
    /// False where a switch cannot stand: a constant is required (default parameter value, case label, pattern),
    /// the expression declares a variable (it would be declared twice), an endless loop would stop being one,
    /// or the code is an expression tree or a query a provider translates.
    /// </summary>
    public static bool CanSwitch(Site site)
    {
        var holder = Holder(site);
        var model = site.File.Model;
        var declares = holder.DescendantNodes().Any(node => node is SingleVariableDesignationSyntax or DeclarationExpressionSyntax);
        var isLoopCondition = holder is LiteralExpressionSyntax && holder.Parent is WhileStatementSyntax or DoStatementSyntax or ForStatementSyntax;
        return !declares && !isLoopCondition && !holder.Ancestors().Any(node => IsBarrier(node, model));
    }

    private static bool IsBarrier(SyntaxNode node, SemanticModel model) => node switch
    {
        PatternSyntax or CaseSwitchLabelSyntax or EqualsValueClauseSyntax { Parent: ParameterSyntax } => true,
        AnonymousFunctionExpressionSyntax => model.GetTypeInfo(node).ConvertedType?.Name == "Expression",
        QueryExpressionSyntax => IsQueryable(model.GetTypeInfo(node).Type),
        _ => false,
    };

    private static bool IsQueryable(ITypeSymbol? type) =>
        type is not null && type.AllInterfaces.Append(type).Any(candidate => candidate.Name == "IQueryable");

    private static string HelperClass(string assembly) =>
        HelperPrefix + string.Concat(assembly.Select(character => char.IsAsciiLetterOrDigit(character) ? character : '_'));

    private static SyntaxNode Holder(Site site) => site.Token.Parent ?? site.File.Tree.GetRoot();

    private static IEnumerable<Edit> Edits(Site site, string helper)
    {
        var holder = Holder(site);
        var text = holder.ToString();
        var at = site.Token.SpanStart - holder.SpanStart;
        var mutated = text[..at] + site.Mutant.Replacement + text[(at + site.Token.Span.Length)..];
        var test = $"global::{helper}.Is({SymbolDisplay.FormatLiteral(site.Mutant.Id, true)})";
        return [TextEdits.Insert(holder.SpanStart, $"({test} ? {mutated} : "), TextEdits.Insert(holder.Span.End, ")")];
    }
}
