using System.Linq;

namespace Gate.CSharp.Tracing;

/// <summary>
/// The source of the runtime helper added to every instrumented project. It has no dependency
/// outside the base class library. The current component lives in one AsyncLocal shared by all
/// instrumented assemblies of the process (found through AppDomain data), so edges between
/// projects are seen; each distinct edge is appended once per process as one whole JSON line.
/// </summary>
internal static class TraceHelper
{
    public const string FileName = "GateTrace.g.cs";

    private const string Template = """
        // <auto-generated/>
        // Written by gate-csharp instrument. Records which component calls which.
        internal static class CLASS
        {
            private const string TraceFile = @"TRACEFILE";
            private static readonly object Gate = string.Intern("gate.trace.lock");

            private static readonly global::System.Threading.AsyncLocal<string> Current =
                Shared<global::System.Threading.AsyncLocal<string>>("gate.trace.current");

            private static readonly global::System.Collections.Concurrent.ConcurrentDictionary<string, bool> Seen =
                Shared<global::System.Collections.Concurrent.ConcurrentDictionary<string, bool>>("gate.trace.seen");

            public static string Enter(string component)
            {
                var previous = Current.Value ?? "";
                if (previous.Length != 0 && component.Length != 0 && previous != component && Seen.TryAdd(previous + "\n" + component, true))
                {
                    Append("{\"from\": " + Quote(previous) + ", \"to\": " + Quote(component) + "}\n");
                }
                Current.Value = component;
                return previous;
            }

            public static void Exit(string previous)
            {
                Current.Value = previous;
            }

            private static T Shared<T>(string key)
                where T : class, new()
            {
                lock (Gate)
                {
                    var existing = global::System.AppDomain.CurrentDomain.GetData(key) as T;
                    if (existing != null)
                    {
                        return existing;
                    }
                    var created = new T();
                    global::System.AppDomain.CurrentDomain.SetData(key, created);
                    return created;
                }
            }

            private static string Quote(string text)
            {
                return "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
            }

            private static void Append(string line)
            {
                var bytes = global::System.Text.Encoding.UTF8.GetBytes(line);
                lock (Gate)
                {
                    using (var stream = new global::System.IO.FileStream(
                        TraceFile,
                        global::System.IO.FileMode.Append,
                        global::System.IO.FileAccess.Write,
                        global::System.IO.FileShare.ReadWrite))
                    {
                        stream.Write(bytes, 0, bytes.Length);
                    }
                }
            }
        }

        """;

    /// <summary>The helper class of one assembly. Each assembly has its own name so internals shared between projects do not clash.</summary>
    public static string ClassName(string assembly) =>
        "GateTrace_" + string.Concat(assembly.Select(character => char.IsAsciiLetterOrDigit(character) ? character : '_'));

    public static string Source(string assembly, string traceFile) =>
        Template.Replace("CLASS", ClassName(assembly)).Replace("TRACEFILE", traceFile.Replace("\"", "\"\""));
}
