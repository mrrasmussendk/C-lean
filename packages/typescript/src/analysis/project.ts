/** Builds the analyzed project from the inputs and the compiled program. */
import * as path from "node:path";
import type * as ts from "typescript";
import type { Component, GateConfig } from "../model/config";
import type { Compilation, Inputs, PackageName } from "../model/inputs";
import type { Project, SourceUnit } from "../model/project";
import { effectUses } from "./effects";
import { matchesAny } from "./glob";
import { parseArchitecture, parseConfig, parseGlossary } from "./settings";
import { suppressionsOf } from "./suppressions";
import { codeLinesOf, commentsOf, tokensOf } from "./tokens";
import { functionUnits, typeUnits } from "./units";

const GENERATED_MARKERS: readonly string[] = ["<auto-generated", "@generated"];
const MARKER_LINES = 5;
const NO_PACKAGE = "-";

interface Build {
  inputs: Inputs;
  program: ts.Program;
  checker: ts.TypeChecker;
  config: GateConfig;
  components: Component[];
}

/** The TypeScript sources among the listed files; declaration files hold no code to analyze. */
export function sourcePaths(files: readonly string[]): string[] {
  return files.filter((file) => /\.tsx?$/.test(file) && !file.endsWith(".d.ts"));
}

export function buildProject(inputs: Inputs, compilation: Compilation, today: string): Project {
  const program = compilation.program;
  const config = parseConfig(inputs.config);
  const build: Build =
    { inputs, program, checker: program.getTypeChecker(), config, components: parseArchitecture(inputs.architecture) };
  return {
    files: sourcePaths(inputs.files).flatMap((file) => sourceUnits(build, file)),
    checker: build.checker,
    config,
    today,
    glossary: parseGlossary(inputs.glossary),
    compiler: compilation.facts,
  };
}

/** The unit of one file; none for a generated file, a file that does not parse or one the program does not hold. */
function sourceUnits(build: Build, relative: string): SourceUnit[] {
  const source = build.program.getSourceFile(path.join(build.inputs.root, relative));
  if (!source || isGenerated(build.config, relative, source.text)) return [];
  if (build.program.getSyntacticDiagnostics(source).length > 0) return [];
  const tokens = tokensOf(source);
  const test = matchesAny(build.config.tests, relative);
  const effects = effectUses(source, build.checker);
  const facts =
    { path: relative, source, test, packageName: packageOf(build.inputs.packages, relative),
      codeLines: codeLinesOf(source, tokens), effects };
  const comments = commentsOf(source, tokens);
  const component = build.components.find((candidate) => matchesAny(candidate.paths, relative));
  return [{
    path: relative,
    source,
    test,
    component: component?.name ?? "",
    effectComponent: component?.effect ?? false,
    comments,
    suppressions: suppressionsOf(comments),
    functions: functionUnits(facts),
    types: typeUnits(facts),
    effects,
  }];
}

function isGenerated(config: GateConfig, relative: string, text: string): boolean {
  const head = text.split("\n").slice(0, MARKER_LINES).join("\n");
  return matchesAny(config.generated, relative) || GENERATED_MARKERS.some((marker) => head.includes(marker));
}

/** The name in the nearest package.json at or above the file, else `-`. */
function packageOf(packages: readonly PackageName[], relative: string): string {
  const holding =
    packages.filter((candidate) => candidate.directory === "" || relative.startsWith(`${candidate.directory}/`));
  const nearest = [...holding].sort((left, right) => right.directory.length - left.directory.length)[0];
  return nearest?.name ?? NO_PACKAGE;
}

/** One line per source file that does not parse: file, line, column and the parser's message. */
export function parseProblems(inputs: Inputs, program: ts.Program): string[] {
  return sourcePaths(inputs.files).flatMap((relative) => {
    const source = program.getSourceFile(path.join(inputs.root, relative));
    const broken = source ? program.getSyntacticDiagnostics(source)[0] : undefined;
    if (!source || !broken) return [];
    const at = source.getLineAndCharacterOfPosition(broken.start ?? 0);
    const message = typeof broken.messageText === "string" ? broken.messageText : broken.messageText.messageText;
    return [`${relative}:${at.line + 1}:${at.character + 1}: the file does not parse: ${message.replace(/\.$/,
      "")}. Fix the syntax; the file was left out of the analysis.`];
  });
}
