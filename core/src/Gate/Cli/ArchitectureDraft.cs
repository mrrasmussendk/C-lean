using Gate.Model;

namespace Gate.Cli;

/// <summary>The architecture.yaml `gate init` proposes: one component per top-level directory, the edges as they are today.</summary>
internal static class ArchitectureDraft
{
    private const string RootComponent = "root";

    public static string Text(Graph graph)
    {
        var components = graph.Nodes.Select(node => Component(node.File)).Distinct().Order().ToList();
        var owner = graph.Nodes.GroupBy(node => node.Id).ToDictionary(group => group.Key, group => Component(group.First().File));
        var edges = graph.Edges
            .Where(edge => owner.ContainsKey(edge.From) && owner.ContainsKey(edge.To) && owner[edge.From] != owner[edge.To])
            .Select(edge => $"  - {{from: {owner[edge.From]}, to: {owner[edge.To]}}}")
            .Distinct().Order();
        var header = "# Generated by `gate init` from the current graph. Edit it: name the components, mark effect components and boundaries.";
        return string.Join('\n', [header, "components:", .. components.Select(Entry), "edges:", .. edges, ""]);
    }

    private static string Component(string file) =>
        file.Contains('/') ? file.Split('/')[0] : RootComponent;

    private static string Entry(string component) =>
        component == RootComponent
            ? $"  - name: {RootComponent}\n    paths: [\"*\"]"
            : $"  - name: {component}\n    paths: [\"{component}/**\"]";
}
