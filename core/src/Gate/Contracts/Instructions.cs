// What the implementer is told before it writes: the limits, the model and the workflow of this repository.
using Gate.Model;

namespace Gate.Contracts;

internal static class Instructions
{
    public const string Begin = "<!-- gate:begin (generated by `gate init` from gate.yaml and architecture.yaml; do not edit) -->";
    public const string End = "<!-- gate:end -->";

    /// <summary>The generated section. It is rebuilt from the configuration, so it cannot drift from what the gate enforces.</summary>
    public static string Block(Config config, Architecture architecture) =>
        string.Join('\n', [Begin, .. Workflow(config), .. Rules(config), .. Model(architecture), End]) + "\n";

    private static IReadOnlyList<string> Workflow(Config config) =>
    [
        "## Clean code gate",
        "",
        "This repository is checked by `gate`. A change that breaks a rule cannot merge. Write to the rules from the first line; do not write first and fix after.",
        "",
        "### How to work",
        "",
        "1. A change starts from an approved change record in `changes/`. If there is none for your task, stop and ask for one (`gate change new <id>`, approved by a human). One change has one reason.",
        "2. After every edit the file is checked and the findings come back to you. Fix the code, not the check.",
        "3. Never edit these paths; a human owns them: " + string.Join(", ", config.Protected.Select(path => $"`{path}`")) + ".",
        "4. Never suppress, disable or route around a rule. No linter or compiler disable switches.",
        $"5. If a rule and the task cannot both be satisfied, or a finding survives {Attempts.Limit} edits, stop and run `gate conflict \"<rule and why>\"`. That is the sanctioned exit; working around the rule is not.",
        "6. Do not modify or delete an existing test unless the change record declares it. A new test must fail for a fault no existing test catches.",
        "7. Before you say the work is done, run `gate check` and read every block and warn.",
        "",
        "`gate explain <rule>` prints a rule's definition and how to fix it.",
        "",
    ];

    private static IReadOnlyList<string> Rules(Config config) =>
    [
        "### Rules",
        "",
        "| Rule | Requirement | Limit | Effect |",
        "| --- | --- | --- | --- |",
        .. RuleTable.Entries.Select(entry => Row(config, entry)),
        "",
    ];

    private static IReadOnlyList<string> Model(Architecture architecture) =>
    [
        "### Components",
        "",
        "Code may depend only along the allowed edges. A new edge must be in the change record before you write it.",
        "",
        .. architecture.Components.Select(Component),
        "",
        "Allowed edges: " + (architecture.Edges.Count == 0 ? "none" : string.Join(", ", architecture.Edges.Select(edge => $"{edge.From} -> {edge.To}"))) + ".",
    ];

    /// <summary>The instruction file with the generated section replaced, or appended when it has none.</summary>
    public static string Merge(string existing, string block)
    {
        var start = existing.IndexOf(Begin, StringComparison.Ordinal);
        var end = existing.IndexOf(End, StringComparison.Ordinal);
        if (start < 0 || end < start)
        {
            return existing.Length == 0 ? block : existing.TrimEnd() + "\n\n" + block;
        }

        return existing[..start] + block.TrimEnd('\n') + existing[(end + End.Length)..];
    }

    private static string Row(Config config, RuleEntry entry)
    {
        var limit = entry.Default.Any(char.IsDigit) ? Settings.Limit(config, entry.Id).ToString() : "";
        return $"| {entry.Id} | {entry.Definition} | {limit} | {Settings.Severity(config, entry.Id).Name} |";
    }

    private static string Component(Component component)
    {
        var marks = new[] { (component.Effect, "effect component: the only place effect APIs may be called"), (component.Boundary, "boundary"), (component.CoreLogic, "core logic: needs a property-based test") }
            .Where(mark => mark.Item1).Select(mark => mark.Item2);
        return $"- `{component.Name}`: {string.Join(", ", component.Paths.Select(path => $"`{path}`"))}{string.Concat(marks.Select(mark => $" ({mark})"))}";
    }
}
